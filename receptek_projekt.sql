CREATE DATABASE receptes_app CHARACTER SET utf8mb4 COLLATE utf8mb4_hungarian_ci;

USE receptes_app;

CREATE TABLE receptek (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nev VARCHAR(100) NOT NULL,
    etel_tipus ENUM('foetel', 'leves', 'desszert') NOT NULL,
    leiras TEXT,
    elkeszitesi_ido_perc INT,
    letrehozva DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE hozzavalok (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nev VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE recept_hozzavalok (
    recept_id INT NOT NULL,
    hozzavalo_id INT NOT NULL,
    mennyiseg DECIMAL(8,2) NOT NULL,
    mertekegyseg VARCHAR(30) NOT NULL,
    PRIMARY KEY (recept_id, hozzavalo_id),
    FOREIGN KEY (recept_id) REFERENCES receptek(id),
    FOREIGN KEY (hozzavalo_id) REFERENCES hozzavalok(id)
);



